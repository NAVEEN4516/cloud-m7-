"""Rebuild fixed controlled fixtures and independently checkable expected results."""
import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from cloud_m7.simulator.attack_scenario import MultiTierAttackSimulator
from cloud_m7.schema.event import ProvenanceEvent
from cloud_m7.fusion.causal_graph import ProvenanceGraphEngine
from cloud_m7.fusion.attack_path import AttackPathReconstructor
from cloud_m7.fusion.interconnected_paths import InterconnectedAttackPathEngine
from cloud_m7.fusion.reduction import fold_repeated_reads

ROOT = Path(__file__).resolve().parents[1]


def main():
    out = ROOT / "data" / "demo"
    out.mkdir(parents=True, exist_ok=True)
    sim = MultiTierAttackSimulator()
    attack = sim.generate_full_simulation_dataset(base_time=1700000000.0, benign_count=36)
    normal = sim.generate_benign_events(base_time=1700000000.0, num_events=12)
    repeated = list(attack)
    parent = "repeated-start"
    repeated.append(ProvenanceEvent(uuid=parent, timestamp=1700000020.0, host_id="edge-sensor-01",
        event_type="Process", payload={"action": "exec", "entity": "sensor_daemon", "is_attack": False}))
    for i in range(20):
        event = ProvenanceEvent(uuid=f"repeated-read-{i:02d}", timestamp=1700000020.01 + i * .01,
            host_id="edge-sensor-01", event_type="File", parents=[parent], payload={
                "action": "read", "entity": "/sys/class/thermal/thermal_zone0/temp",
                "pid": 1042, "process": "sensor_daemon", "is_attack": False})
        repeated.append(event)
        parent = event.uuid
    repeated.append(ProvenanceEvent(uuid="repeated-end", timestamp=1700000020.5, host_id="edge-sensor-01",
        event_type="Process", parents=[parent], payload={"action": "exec", "entity": "flush_metrics", "is_attack": False}))
    manifest = {"provenance": "Controlled synthetic fixtures generated by CLOUD-M7; not public benchmark captures",
        "base_time_unix": 1700000000.0, "labels": "is_attack is supplied ground truth, not a detector prediction", "datasets": {}}
    for name, events in [("normal", normal), ("attack", attack), ("repeated", repeated)]:
        rows = [e.to_dict() for e in sorted(events, key=lambda e: (e.timestamp, e.uuid))]
        (out / f"{name}.json").write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8")
        with (out / f"{name}.csv").open("w", encoding="utf-8", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=["uuid", "timestamp", "tier", "host_id", "event_type", "payload_json", "parents_json", "tamper_hash"])
            writer.writeheader()
            for row in rows:
                row = dict(row)
                row["payload_json"] = json.dumps(row.pop("payload"), sort_keys=True)
                row["parents_json"] = json.dumps(row.pop("parents"))
                writer.writerow(row)
        engine = ProvenanceGraphEngine(15)
        engine.add_events(events)
        graph = engine.fuse_global_graph()
        path = AttackPathReconstructor(engine).reconstruct_attack_path()
        sensors = InterconnectedAttackPathEngine(engine).analyze_interconnected_attack_graph()
        reduction = fold_repeated_reads(graph)
        manifest["datasets"][name] = {
            "events": len(events), "attack_labelled_events": sum(bool(e.payload.get("is_attack")) for e in events),
            "normal_events": sum(not e.payload.get("is_attack") for e in events),
            "edges": graph.number_of_edges(), "cross_tier_flows": engine.get_summary_statistics()["cross_tier_edges_count"],
            "primary_path_events": path.path_length if path else 0,
            "originating_sensors": sorted(sensors.originating_sensors),
            "reduced_nodes": len(reduction.graph), "node_reduction_pct": reduction.metrics["node_reduction_pct"],
        }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest["datasets"], indent=2))


if __name__ == "__main__":
    main()
